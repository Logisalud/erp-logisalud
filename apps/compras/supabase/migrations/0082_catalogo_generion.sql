-- Lista entregada por el usuario el 2026-10-22 (GENERION_LISTA.xlsx, 40
-- filas). Cada fila trae su CÓDIGO LOGISALUD (GNR1xx/GNR2xx) y su CÓDIGO
-- BONIFICACIÓN (BOGNR…), así que entran DOS filas por producto, igual que el
-- resto del catálogo: el regular, que se compra, y el bonificado, que llega
-- sin costo. El vínculo queda declarado en `codigo_bonificacion` del regular,
-- que es de donde lo lee todo el módulo (ver 0070).
--
-- ── El precio ────────────────────────────────────────────────────────────
-- El Excel trae PVF **CON IGV** y `catalogo.productos.precio_compra` es
-- NETO: la OC le suma el 18% encima (`separarPorIgv` en
-- domain/orden-compra.ts). Así que se carga PVF / 1.18, con los 4 decimales
-- que admite la columna. Reconstruido al revés, las 40 filas vuelven a dar
-- el precio del archivo al céntimo.
--
-- El bonificado va en **0.00 y no en null**: pedido explícito del usuario
-- —"que este esté en costo 0"— y es lo que hace que el formulario de la OC
-- traiga la línea ya valorizada en cero en vez de pedir que la tipeen. Ojo
-- que los otros 242 bonificados del catálogo tienen `precio_compra` null;
-- esta es la primera tanda cargada en cero, a propósito.
--
-- ── IGV ──────────────────────────────────────────────────────────────────
-- Las 40 filas dicen AFECTO IGV = SI, así que `exonerado_igv` queda en
-- false, que es el default. No se toca nada de 0078/0079.
--
-- ── Qué NO entra ─────────────────────────────────────────────────────────
-- `proveedor_id` queda null: Generion todavía no existe en
-- `compras.proveedores` y para darlo de alta hace falta su RUC. No impide
-- usarlos — el buscador de la OC no filtra por proveedor —, pero hay que
-- completarlo. La columna CÓDIGO DIMEXA del Excel tampoco se guarda: no hay
-- dónde, y es el código de otro distribuidor, no de Generion.
--
-- `codigo_proveedor` lleva el CÓDIGO GENERION (EN-xxxxx) solo en la fila
-- regular: es el código del proveedor para ese producto, y repetirlo en el
-- bonificado dejaría dos filas reclamando el mismo.
--
-- Re-ejecutable: `on conflict (codigo) do nothing`.

