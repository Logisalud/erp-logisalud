with fuente as (
  select lpad(btrim(ruc), 11, '0') as ruc, ubigeo, btrim(direccion) as direccion
  from tmp_direcciones_gre
),
cruce as (
  select distinct on (c.id) c.id as customer_id, f.ubigeo, f.direccion
  from fuente f
  join pedidos.customers c on lpad(btrim(c.ruc_o_documento), 11, '0') = f.ruc
  where not exists (select 1 from pedidos.customer_addresses a where a.customer_id = c.id)
  order by c.id, f.ruc
)
insert into pedidos.customer_addresses (customer_id, direccion, ubigeo, es_principal, estado)
select customer_id, direccion, ubigeo, true, 'activo' from cruce;

-- Y las direcciones que ya existían sin ubigeo: el nombre del distrito
-- está en `customers`, no en la dirección, así que el cruce sale de ahí.
update pedidos.customer_addresses a
set ubigeo = pedidos.resolver_ubigeo(c.departamento, c.provincia, c.distrito)
from pedidos.customers c
where c.id = a.customer_id
  and coalesce(btrim(a.ubigeo), '') = ''
  and pedidos.resolver_ubigeo(c.departamento, c.provincia, c.distrito) is not null;
