// S4: rutas de distribución en los 4 viewports: lista, armado (vehículo, personal, pedidos, orden), corte, vehículo calificado, sin stock, versiones y permisos.
import { expect, test, type Page } from '@playwright/test'
import { capturar, entrarComo, esTelefono, sinDesborde } from './ayudas'

test.describe.configure({ mode: 'serial' })

/** La bandeja con el pedido nuevo (104, sin stock suficiente) y el 102 ya revisado, sin importar qué pasó antes en esta sesión. */
async function prepararBandeja(page: Page, info: { project: { name: string } }) {
  await page.goto('/wms/pedidos')
  await page.getByTestId('actualizar-bandeja').click()
  await expect(page.getByTestId('bandeja-resumen')).toBeVisible()
  await expect(page.getByTestId('ped-conteo')).toHaveText('4 pedidos')
  const fila = (n: string) => (info.project.name.startsWith('telefono') ? page.getByTestId('fila-pedido-movil') : page.getByTestId('fila-pedido')).filter({ hasText: n })
  if ((await fila('PED-DEMO-102').textContent())?.includes('Cambió: revisar')) {
    await (info.project.name.startsWith('telefono') ? fila('PED-DEMO-102').getByTestId('abrir-pedido-movil') : fila('PED-DEMO-102').getByTestId('abrir-pedido')).click()
    await page.locator('[data-testid="detalle-pedido"]:visible').getByTestId('pedido-revisar-cambio').click()
    await expect(fila('PED-DEMO-102')).toContainText('Por planificar')
  }
}

test.describe('rutas (S4)', () => {
  test('el Jefe de Transporte ve las rutas con su estado y abre la ruta ya planificada', async ({ page }, info) => {
    await entrarComo(page, 'jefe_transporte')
    await page.goto('/wms/rutas')
    await expect(page.getByTestId('lista-rutas')).toBeVisible()
    const fila = page.getByTestId(esTelefono(info) ? 'fila-ruta-movil' : 'fila-ruta').first()
    await expect(fila).toContainText('Planificada')
    await expect(fila).toContainText('BKW-757')
    await sinDesborde(page)
    await capturar(page, info, 'rutas-lista', { completa: true })
    await (esTelefono(info) ? fila : fila.getByRole('link', { name: /^Abrir/ })).click()
    await expect(page.getByTestId('editor-ruta')).toBeVisible()
    await expect(page.getByTestId('parada')).toHaveCount(1)
    await expect(page.getByTestId('parada').first()).toContainText('Botica Salud Total SAC')
    await expect(page.getByTestId('parada').first().getByTestId('chip-stock-parada')).toContainText('Stock asignado')
    await expect(page.getByTestId('historial-ruta')).toContainText('Versión 1')
    await sinDesborde(page)
    await capturar(page, info, 'rutas-editor', { completa: true })
  })

  test('el formato LS-FR.43.03 nace con la ruta confirmada: panel con sus pendientes de Dirección Técnica y PDF horizontal; la ruta en borrador todavía no lo tiene', async ({ page }, info) => {
    await entrarComo(page, 'jefe_transporte')
    await page.goto('/wms/rutas')
    const planificada = page.getByTestId(esTelefono(info) ? 'fila-ruta-movil' : 'fila-ruta').filter({ hasText: 'Planificada' }).first()
    await (esTelefono(info) ? planificada : planificada.getByRole('link', { name: /^Abrir/ })).click()
    await expect(page.getByTestId('lsfr-panel')).toContainText('LS-FR.43.03')
    await page.getByTestId('lsfr-definiciones').locator('summary').click()
    await expect(page.getByTestId('lsfr-definiciones')).toContainText('Qué significa la columna USUARIO')
    await sinDesborde(page)
    await capturar(page, info, 'rutas-lsfr-panel', { completa: true })
    const href = await page.getByTestId('ver-lsfr').getAttribute('href')
    const r = await page.request.get(href!)
    expect(r.status()).toBe(200)
    expect(r.headers()['content-type']).toContain('application/pdf')
    const cuerpo = await r.body()
    expect(cuerpo.subarray(0, 4).toString()).toBe('%PDF')
    expect(cuerpo.length).toBeGreaterThan(5_000)
    if (info.project.name.startsWith('desktop')) (await import('node:fs')).writeFileSync('/tmp/claude-0/lsfr-demo.pdf', cuerpo)
    // una ruta en borrador no tiene registro todavía
    await page.goto('/wms/rutas')
    await page.getByTestId('nueva-ruta').click()
    await expect(page.getByTestId('lsfr-pendiente')).toContainText('Se crea cuando confirmas la ruta')
    const id = page.url().split('/').pop()!
    expect((await page.request.get(`/wms/rutas/${id}/pdf`)).status()).toBe(404)
  })

  test('armar una ruta nueva: vehículo, personal, un pedido, orden; guardar y confirmar (nace el LS-FR.43.03)', async ({ page }, info) => {
    await entrarComo(page, 'jefe_transporte')
    await prepararBandeja(page, info)
    await page.goto('/wms/rutas')
    await page.getByTestId('nueva-ruta').click()
    await expect(page.getByTestId('editor-ruta')).toBeVisible()
    await expect(page.getByTestId('sin-paradas')).toBeVisible()
    await expect(page.getByTestId('confirmar-ruta')).toBeDisabled()
    await page.getByTestId('ruta-vehiculo').selectOption({ label: 'D4F-318 — Furgón con termo · calificado · frío' })
    await page.getByTestId('ruta-conductor').selectOption({ label: 'Marco Huamán' })
    await page.getByTestId('ruta-auxiliar').selectOption({ label: 'Pedro Soto' })
    await page.getByTestId('agregar-buscar').fill('angeles')
    await page.getByTestId('pedido-disponible').filter({ hasText: 'PED-DEMO-102' }).getByTestId('agregar-pedido').click()
    await expect(page.getByTestId('parada')).toHaveCount(1)
    await expect(page.getByTestId('conteo-paradas')).toHaveText('(1)')
    // Un pedido que Pedidos modificó pasadas las 16:00 llega después del corte de la víspera: depende de la hora en que se pruebe
    if (await page.getByTestId('excepcion-corte').count()) { await page.getByTestId('excepcion-corte').check(); await page.getByTestId('excepcion-motivo').fill('Cliente urgente') }
    await sinDesborde(page)
    await capturar(page, info, 'rutas-armando', { completa: true })
    await page.getByTestId('guardar-plan').click()
    await expect(page.getByTestId('ruta-ok')).toContainText('Plan guardado')
    await expect(page.getByTestId('parada').first().getByTestId('chip-stock-parada')).toContainText('Stock asignado')
    await page.getByTestId('confirmar-ruta').click()
    await expect(page.getByTestId('ruta-ok')).toContainText('LS-FR.43.03')
    await expect(page.getByTestId('chip-estado-ruta').first()).toContainText('Planificada')
    await expect(page.getByTestId('historial-ruta')).toContainText('Versión 2')
  })

  test('el vehículo común no atiende al cliente que exige calificado, y un pedido sin stock deja guardar pero no confirmar; sacarlo lo libera', async ({ page }, info) => {
    await entrarComo(page, 'jefe_transporte')
    await page.goto('/wms/rutas')
    await page.getByTestId('nueva-ruta-fecha').fill(new Date().toISOString().slice(0, 10)) // hoy: lo importado hoy llegó después del corte de la víspera
    await page.getByTestId('nueva-ruta').click()
    await expect(page.getByTestId('editor-ruta')).toBeVisible()
    await page.getByTestId('ruta-vehiculo').selectOption({ label: 'AXL-204 — Moto furgón' })
    await page.getByTestId('ruta-conductor').selectOption({ label: 'Luis Quispe' })
    await page.getByTestId('agregar-buscar').fill('PED-DEMO-104')
    await page.getByTestId('pedido-disponible').filter({ hasText: 'PED-DEMO-104' }).getByTestId('agregar-pedido').click()
    await expect(page.getByTestId('errores-plan')).toContainText('exige un vehículo calificado')
    await expect(page.getByTestId('errores-plan')).toContainText('llegó después del corte')
    await expect(page.getByTestId('guardar-plan')).toBeDisabled()
    await page.getByTestId('ruta-vehiculo').selectOption({ label: 'BKW-757 — Camioneta cerrada · calificado' })
    await page.getByTestId('excepcion-corte').check()
    await page.getByTestId('excepcion-motivo').fill('Cliente urgente')
    await expect(page.getByTestId('errores-plan')).toHaveCount(0)
    await capturar(page, info, 'rutas-corte', { completa: true })
    await page.getByTestId('guardar-plan').click()
    await expect(page.getByTestId('aviso-bloqueados')).toContainText('PED-DEMO-104')
    await expect(page.getByTestId('parada').first().getByTestId('chip-stock-parada')).toContainText('Sin stock suficiente')
    await page.getByTestId('confirmar-ruta').click()
    await expect(page.getByTestId('ruta-error')).toContainText('no tienen stock suficiente')
    await capturar(page, info, 'rutas-sin-stock', { completa: true })
    await page.getByTestId('parada-quitar').click()
    await page.getByTestId('guardar-plan').click()
    await expect(page.getByTestId('ruta-ok')).toContainText('Plan guardado')
    await expect(page.getByTestId('sin-paradas')).toBeVisible()
  })

  test('cambiar una ruta ya planificada pide el motivo y queda en el historial; cancelarla libera el pedido', async ({ page }, info) => {
    await entrarComo(page, 'jefe_transporte')
    await page.goto('/wms/rutas')
    const planificada = page.getByTestId(esTelefono(info) ? 'fila-ruta-movil' : 'fila-ruta').filter({ hasText: 'Planificada' }).first()
    await (esTelefono(info) ? planificada : planificada.getByRole('link', { name: /^Abrir/ })).click()
    await expect(page.getByTestId('editor-ruta')).toBeVisible()
    await page.getByTestId('parada-quitar').first().click()
    await expect(page.getByTestId('guardar-plan')).toBeDisabled()
    await page.getByTestId('ruta-motivo').fill('Se reprograma la entrega')
    await page.getByTestId('guardar-plan').click()
    await expect(page.getByTestId('ruta-ok')).toContainText('Plan guardado')
    await expect(page.getByTestId('historial-ruta')).toContainText('Se reprograma la entrega')
    await page.getByTestId('abrir-cancelar').click()
    await expect(page.getByTestId('cancelar-confirmar')).toBeDisabled()
    await page.getByTestId('cancelar-motivo').fill('Cliente cerrado')
    await capturar(page, info, 'rutas-cancelar')
    await page.getByTestId('cancelar-confirmar').click()
    await page.waitForURL(/\/wms\/rutas\/?$/)
    await expect(page.getByTestId(esTelefono(info) ? 'fila-ruta-movil' : 'fila-ruta').filter({ hasText: 'Cancelada' }).first()).toBeVisible()
  })

  test('personal y vehículos: el Jefe de Transporte agrega a un conductor y un vehículo; no se repiten', async ({ page }, info) => {
    await entrarComo(page, 'jefe_transporte')
    await page.goto('/wms/rutas/recursos')
    await expect(page.getByTestId('recursos-ruta')).toBeVisible()
    await page.getByTestId('nuevo-CONDUCTOR').fill('Teresa Mamani')
    await page.getByTestId('guardar-CONDUCTOR').click()
    await expect(page.getByTestId('fila-personal').filter({ hasText: 'Teresa Mamani' })).toBeVisible()
    await page.getByTestId('vehiculo-placa').fill('NEW-123')
    await page.getByTestId('vehiculo-calificado').check()
    await page.getByTestId('guardar-vehiculo').click()
    await expect(page.getByTestId('fila-vehiculo').filter({ hasText: 'NEW-123' })).toContainText('Calificado')
    await page.getByTestId('vehiculo-placa').fill('NEW-123')
    await page.getByTestId('guardar-vehiculo').click()
    await expect(page.getByText('Ya existe')).toBeVisible()
    await sinDesborde(page)
    await capturar(page, info, 'rutas-recursos', { completa: true })
  })

  test('el Jefe de Almacén «solo» ve las rutas pero no planifica; el auxiliar no entra', async ({ page }) => {
    await entrarComo(page, 'reemplazante_jefe')
    await page.goto('/wms/rutas')
    await expect(page.getByTestId('lista-rutas')).toBeVisible()
    await expect(page.getByTestId('nueva-ruta')).toHaveCount(0)
    await entrarComo(page, 'auxiliar')
    await page.goto('/wms/rutas')
    await expect(page.getByTestId('rutas-sin-permiso')).toBeVisible()
  })
})
