// S6a: repositorio de documentos regulatorios, carga masiva de COA y perfiles documentales, en los 4 viewports.
import { expect, test, type Page } from '@playwright/test'
import { capturar, entrarComo, esTelefono, sinDesborde } from './ayudas'

test.describe.configure({ mode: 'serial' })

const pdf = (nombre: string) => ({ name: nombre, mimeType: 'application/pdf', buffer: Buffer.from(`%PDF-1.4\n% ${nombre}\n%%EOF\n`) })
const filaDoc = (page: Page, info: { project: { name: string } }) => page.getByTestId(info.project.name.startsWith('telefono') ? 'fila-documento-movil' : 'fila-documento')

test.describe('documentos regulatorios (S6a)', () => {
  test('Dirección Técnica ve el repositorio con su resumen, lo vencido primero y los lotes sin COA', async ({ page }, info) => {
    await entrarComo(page, 'direccion_tecnica')
    await page.goto('/wms/documentos')
    await expect(page.getByTestId('repositorio-documentos')).toBeVisible()
    await expect(page.getByTestId('resumen-vencidos')).toContainText('1')
    await expect(page.getByTestId('resumen-porVencer')).toContainText('1')
    await expect(page.getByTestId('aviso-sin-coa')).toContainText('no tienen COA')
    await expect(page.getByTestId('aviso-por-revisar')).toContainText('3 archivos de COA')
    await expect(filaDoc(page, info).first()).toContainText('Vencido')
    await sinDesborde(page)
    await capturar(page, info, 'documentos-repositorio', { completa: true })
    // el filtro por estado deja solo lo por vencer
    await page.getByTestId('resumen-porVencer').click()
    await expect(page.getByTestId('doc-conteo')).toHaveText('1 documento')
  })

  test('el auxiliar adjunta el COA de un lote sin COA, pero no puede subir un registro sanitario', async ({ page }, info) => {
    await entrarComo(page, 'auxiliar')
    await page.goto('/wms/documentos')
    await page.getByTestId('adjuntar-coa').first().click()
    await expect(page.getByTestId('form-subida')).toBeVisible()
    await expect(page.getByTestId('subida-alcance')).toContainText('Lote')
    await page.getByTestId('subida-archivo').setInputFiles(pdf('coa-auxiliar.pdf'))
    await capturar(page, info, 'documentos-subida')
    await page.getByTestId('subida-guardar').click()
    await expect(page.getByTestId('aviso-ok')).toContainText('Documento guardado')
    await page.getByTestId('abrir-subida').click()
    await page.getByTestId('subida-tipo-REGISTRO_SANITARIO').click()
    await expect(page.getByTestId('subida-no-puede')).toContainText('Solo Dirección Técnica')
    await expect(page.getByTestId('subida-guardar')).toBeDisabled()
  })

  test('Dirección Técnica reemplaza un registro sanitario y la versión anterior queda en el historial', async ({ page }, info) => {
    await entrarComo(page, 'direccion_tecnica')
    await page.goto('/wms/documentos')
    await page.getByTestId('doc-filtro-REGISTRO_SANITARIO').click()
    const f = filaDoc(page, info).filter({ hasText: 'Dapagliflozina' })
    await (info.project.name.startsWith('telefono') ? f.getByRole('button', { name: 'Reemplazar' }) : f.getByTestId('reemplazar-documento')).click()
    await expect(page.getByTestId('subida-alcance')).toContainText('Dapagliflozina')
    await page.getByTestId('subida-archivo').setInputFiles(pdf('rs-nuevo.pdf'))
    await page.getByTestId('subida-hasta').fill('2031-12-31')
    await page.getByTestId('subida-motivo').fill('Renovación')
    await page.getByTestId('subida-guardar').click()
    await expect(page.getByTestId('aviso-ok')).toContainText('anterior quedó en el historial')
    await page.getByTestId('doc-buscar').fill('Dapagliflozina')
    const nueva = filaDoc(page, info).filter({ hasText: 'rs-nuevo.pdf' }).first()
    await expect(nueva).toContainText('Vigente')
    if (esTelefono(info)) await nueva.getByRole('button', { name: 'Versiones' }).click()
    else await nueva.getByTestId('abrir-historial').click()
    await expect(page.getByTestId('historial-documento').first()).toContainText('Motivo: Renovación')
    await capturar(page, info, 'documentos-historial', { completa: true })
  })

  test('la carga en bloque relaciona lo que reconoce y deja lo demás por revisar, donde se asigna o se descarta', async ({ page }, info) => {
    await entrarComo(page, 'jefe_almacen')
    await page.goto('/wms/documentos/carga')
    await page.getByTestId('carga-archivos').setInputFiles([pdf('COA_L-VENCE-PRONTO_Losartan.pdf'), pdf('scan-raro-0007.pdf'), { name: 'notas.txt', mimeType: 'text/plain', buffer: Buffer.from('x') }])
    await expect(page.getByTestId('carga-resumen')).toContainText('2 archivos leídos')
    await expect(page.getByTestId('carga-resumen')).toContainText('1 quedaron como COA vigente')
    await expect(page.getByTestId('carga-resumen')).toContainText('Solo se aceptan archivos PDF')
    await expect(page.getByTestId('lista-por-revisar')).toContainText('scan-raro-0007.pdf')
    await sinDesborde(page)
    await capturar(page, info, 'documentos-carga', { completa: true })
    // el ambiguo se asigna a mano a uno de sus candidatos; los demás se descartan
    const ambiguo = page.getByTestId('item-por-revisar').filter({ hasText: 'COA ambiguo.pdf' })
    await ambiguo.getByTestId('item-lote').selectOption({ index: 1 })
    await ambiguo.getByTestId('item-asignar').click()
    await expect(page.getByTestId('item-por-revisar').filter({ hasText: 'COA ambiguo.pdf' })).toHaveCount(0)
    const sobrante = page.getByTestId('item-por-revisar').first()
    await sobrante.getByTestId('item-descartar').click()
    await expect(page.getByTestId('item-por-revisar')).toHaveCount(2)
  })

  test('el Jefe de Transporte define lo que pide un cliente; quien no tiene permiso ve el motivo', async ({ page }, info) => {
    await entrarComo(page, 'jefe_transporte')
    await page.goto('/wms/documentos/perfiles')
    await expect(page.getByTestId('perfiles-documentales')).toBeVisible()
    await page.getByTestId('perfil-nuevo').click()
    const nueva = page.getByTestId('perfil-fila').first()
    await nueva.getByTestId('perfil-ruc').fill('20111222333')
    await nueva.getByTestId('perfil-exigeBpm').check()
    await nueva.getByTestId('perfil-guardar').click()
    await expect(page.getByTestId('perfil-fila').filter({ hasText: '20111222333' })).toBeVisible()
    await sinDesborde(page)
    await capturar(page, info, 'documentos-perfiles', { completa: true })
    await entrarComo(page, 'auxiliar')
    await page.goto('/wms/documentos/perfiles')
    await expect(page.getByTestId('perfiles-sin-permiso')).toBeVisible()
  })
})
