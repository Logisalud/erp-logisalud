import { expect, test, type Page } from '@playwright/test'
import { capturar, entrarComo, sinDesborde, type RolDemo } from './ayudas'

test.describe.configure({ mode: 'serial' })

const estado = { retorno: '', cliente: '', actaCliente: '' }
const PDF = { name: 'dictamen-ajr.pdf', mimeType: 'application/pdf', buffer: Buffer.from('%PDF-1.4\n1 0 obj<<>>endobj\ntrailer<<>>\n%%EOF') }

async function cambiarRol(page: Page, rol: RolDemo) {
  await page.getByTestId('cambiar-rol-demo').selectOption(rol)
  await page.waitForTimeout(400)
  await page.reload()
  await expect(page.getByTestId('banner-demo')).toBeVisible()
}

async function abrirSolicitud(page: Page, numero: string) {
  await page.goto('/wms/entradas')
  await page.getByRole('link', { name: new RegExp(numero) }).filter({ visible: true }).first().click()
  await expect(page.getByTestId('titulo-solicitud')).toHaveText(numero)
}

async function firmarActa(page: Page) {
  await page.getByTestId('generar-acta').click()
  await expect(page.getByTestId('numero-acta')).toHaveText(/^I-\d{6}-\d{4}$/)
  await page.getByTestId('firmar-JEFE_ALMACEN').click()
  await expect(page.getByTestId('firma-JEFE_ALMACEN')).toContainText('Firmó')
  await cambiarRol(page, 'direccion_tecnica')
  await page.getByTestId('firmar-DIRECCION_TECNICA').click()
  await expect(page.getByTestId('firma-DIRECCION_TECNICA')).toContainText('Firmó')
  await cambiarRol(page, 'auxiliar')
  await page.getByTestId('firmar-RESPONSABLE_CONTEO').click()
  await expect(page.getByTestId('firma-RESPONSABLE_CONTEO')).toContainText('Firmó')
  await page.getByTestId('abrir-transportista').click()
  await page.getByLabel('Nombre completo').fill('Pedro Quispe')
  await page.getByLabel('DNI').fill('45678912')
  await page.getByTestId('lienzo-firma').scrollIntoViewIfNeeded()
  const caja = (await page.getByTestId('lienzo-firma').boundingBox())!
  await page.mouse.move(caja.x + 20, caja.y + 40)
  await page.mouse.down()
  await page.mouse.move(caja.x + 90, caja.y + 100, { steps: 6 })
  await page.mouse.move(caja.x + 150, caja.y + 50, { steps: 6 })
  await page.mouse.up()
  await page.getByTestId('firmar-transportista').click()
  await expect(page.getByTestId('firma-TRANSPORTISTA')).toContainText('Firmó')
}

/** Recibe y confirma una solicitud ya autorizada: verifica las líneas, datos, acta con cuatro firmas y confirmar. */
async function recibirYConfirmar(page: Page, numero: string) {
  await entrarComo(page, 'jefe_almacen')
  await abrirSolicitud(page, numero)
  if (await page.getByTestId('iniciar-recepcion').count()) await page.getByTestId('iniciar-recepcion').click()
  await expect(page.getByTestId('coincide').first()).toBeVisible()
  const n = await page.getByTestId('coincide').count()
  for (let i = 0; i < n; i++) await page.getByTestId('coincide').first().click()
  await expect(page.getByTestId('progreso-verificacion')).toContainText(`Verificadas ${n} de ${n}`)
  await page.getByLabel(/Temperatura/).fill('21')
  await page.getByLabel('Placa del vehículo').fill('ABC-123')
  await page.getByTestId('guardar-datos').click()
  await expect(page.getByText('Datos de la recepción guardados.')).toBeVisible()
  await firmarActa(page)
  await cambiarRol(page, 'jefe_almacen')
  await page.getByTestId('confirmar-ingreso').click()
  await expect(page.getByTestId('ingreso-confirmado')).toBeVisible()
}

/** Sandra llena el acta organoléptica del lote y la envía a Dirección Técnica. */
async function llenarYEnviarActa(page: Page, lote: string) {
  await cambiarRol(page, 'asistente_dt')
  await page.goto('/wms/calidad')
  await page.getByTestId('fila-organoleptica').filter({ hasText: `Lote ${lote}` }).first().click()
  await page.getByTestId('marcar-conformes').click()
  await page.getByRole('checkbox', { name: 'Envase de plástico' }).click()
  await page.getByTestId('marcar-conformes').click()
  await page.getByRole('group', { name: /Trae certificado/ }).getByRole('radio', { name: 'Sí' }).click()
  await page.getByRole('group', { name: /Destino que sugieres/ }).getByRole('radio', { name: 'Aprobado' }).click()
  await page.getByTestId('enviar-dt').click()
  await expect(page.getByText('Ya está en la cola de Dirección Técnica')).toBeVisible()
}

test.describe('retornos: una recepción tipo devolución', () => {
  test('la lista de retornos explica que todo vuelve como devolución y que reprogramar es una nueva Orden de Salida', async ({ page }, info) => {
    await entrarComo(page, 'jefe_transporte')
    await page.goto('/wms/retornos')
    await expect(page.getByRole('heading', { name: 'Retornos' })).toBeVisible()
    await expect(page.getByTestId('ayuda-retorno')).toContainText('entra como una devolución')
    await expect(page.getByTestId('lista-salidas-retorno')).toBeVisible()
    await sinDesborde(page)
    await capturar(page, info, 'retornos-lista', { completa: true })
  })

  test('el auxiliar no ve la pantalla de retornos', async ({ page }) => {
    await entrarComo(page, 'auxiliar')
    await page.goto('/wms/retornos')
    await expect(page.getByTestId('retornos-sin-permiso')).toBeVisible()
  })

  test('Roberto registra el retorno: pide motivo y factura, no deja devolver más de lo que salió y dice qué sigue', async ({ page }, info) => {
    await entrarComo(page, 'jefe_transporte')
    await page.goto('/wms/retornos')
    await page.getByTestId('registrar-retorno').first().click()
    await expect(page.getByTestId('form-retorno')).toBeVisible()
    await expect(page.getByTestId('linea-retorno').first()).toContainText('pueden volver 30')
    await page.getByTestId('registrar-retorno-enviar').click()
    await expect(page.getByText('Elige por qué vuelve: rechazado por el cliente o no entregado.')).toBeVisible()
    await sinDesborde(page)
    await capturar(page, info, 'retorno-formulario-error', { completa: true })

    await page.getByTestId('motivo-RECHAZADO_CLIENTE').click()
    await page.getByTestId('cantidad-retorno').first().fill('31')
    await page.getByTestId('registrar-retorno-enviar').click()
    await expect(page.getByTestId('form-retorno')).toContainText('solo puede volver 30')
    await page.getByTestId('cantidad-retorno').first().fill('12')
    await page.getByTestId('registrar-retorno-enviar').click()
    await expect(page.getByText('Escribe la factura o boleta original')).toBeVisible()
    await page.getByTestId('retorno-doc-numero').fill('F001-5501')
    await page.getByTestId('registrar-retorno-enviar').click()
    const ok = page.getByTestId('retorno-registrado')
    await expect(ok).toContainText('Retorno registrado')
    await expect(ok).toContainText('Siguiente: Sandra o Katia autorizan la solicitud')
    estado.retorno = ((await page.getByTestId('ir-solicitud-retorno').textContent()) ?? '').trim()
    expect(estado.retorno).toMatch(/^SI-\d{4}-\d{5}$/)
    await expect(page.getByTestId('retornos-previos')).toContainText(estado.retorno)
    await sinDesborde(page)
    await capturar(page, info, 'retorno-registrado', { completa: true })
  })

  test('la solicitud del retorno dice de qué Orden de Salida vuelve; Sandra la autoriza y el conteo es siempre al 100 %', async ({ page }, info) => {
    await entrarComo(page, 'asistente_dt')
    await abrirSolicitud(page, estado.retorno)
    await expect(page.getByTestId('aviso-retorno')).toContainText('Es el retorno de la Orden de Salida SAL-')
    await expect(page.getByTestId('aviso-retorno')).toContainText('rechazado por el cliente')
    await expect(page.getByText('Por autorizar').first()).toBeVisible()
    await sinDesborde(page)
    await capturar(page, info, 'retorno-solicitud', { completa: true })
    await page.getByTestId('autorizar-solicitud').click()
    await expect(page.getByText('Por llegar').first()).toBeVisible()
    await cambiarRol(page, 'jefe_almacen')
    await page.getByTestId('iniciar-recepcion').click()
    await expect(page.getByTestId('conteo-devolucion')).toContainText('al 100 %')
    await expect(page.locator('#conteo')).toBeDisabled()
  })

  test('recibido el retorno, su acta organoléptica evalúa el 100 % de las unidades y el producto está en Devoluciones', async ({ page }, info) => {
    await recibirYConfirmar(page, estado.retorno)
    await cambiarRol(page, 'asistente_dt')
    await page.goto('/wms/calidad')
    await page.getByTestId('fila-organoleptica').filter({ hasText: /12 und/ }).first().click()
    await expect(page.getByTestId('muestra')).toContainText('Evalúa las 12 unidades del lote (el 100 %')
    await expect(page.getByTestId('regimen-muestreo')).toContainText('Devolución · tabla LS-TB.02.02')
    await sinDesborde(page)
    await capturar(page, info, 'acta-organoleptica-retorno', { completa: true })
  })
})

